# for loop  for Lists
l = [1, 93, 384, 9 ,44, 0, 384, "Buggu"]
print(type(l))
for a in l:
    print(a)


# for loop  for Tuples
t = (3, 2943,393, 99, 6,490,4433)
for p in t:
    print(p)
print(type(t))


# for loop  for String
s = "NemasisKyzag"
for o in s:
    print(o)
